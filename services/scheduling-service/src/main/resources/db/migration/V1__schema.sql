CREATE TABLE production (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    start_date  DATE         NOT NULL,
    end_date    DATE         NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT production_dates CHECK (end_date >= start_date)
);

CREATE TABLE shoot_day (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_id  BIGINT       NOT NULL REFERENCES production (id) ON DELETE CASCADE,
    unit           VARCHAR(50)  NOT NULL,
    location_name  VARCHAR(200) NOT NULL,
    call_at        TIMESTAMP    NOT NULL,
    wrap_at        TIMESTAMP    NOT NULL,
    notes          VARCHAR(2000),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT shoot_day_window CHECK (wrap_at > call_at)
);
CREATE INDEX idx_shoot_day_production ON shoot_day (production_id, call_at);

CREATE TABLE assignment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shoot_day_id    BIGINT       NOT NULL REFERENCES shoot_day (id) ON DELETE CASCADE,
    crew_member_id  VARCHAR(64)  NOT NULL,
    role            VARCHAR(100) NOT NULL,
    CONSTRAINT uq_assignment UNIQUE (shoot_day_id, crew_member_id)
);
CREATE INDEX idx_assignment_crew ON assignment (crew_member_id);
